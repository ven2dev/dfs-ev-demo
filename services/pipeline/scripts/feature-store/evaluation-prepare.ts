import { mkdtemp, realpath, mkdir, writeFile } from "node:fs/promises";
import { arch, platform } from "node:os";
import { withFeatureStoreDatabase } from "./harness.ts";
import { EVALUATION_ROOT, evaluationCodeIdentity, prepareEvaluationFixture, verifyPreregistration } from "./evaluation-fixture.ts";
import { openLocalObjectStore } from "../../src/featureStore/localObjectStore.ts";
import { objectKey, sha256 } from "../../src/featureStore/objectStore.ts";

// No evaluation/scorer import: preparation only. Full artifacts stay out of Git.
await verifyPreregistration();
const storageRoot = await realpath(await mkdtemp("/private/tmp/dfs164-evaluation-"));
const store = await openLocalObjectStore(storageRoot);
const { code, codeHashes } = await evaluationCodeIdentity();
const started = performance.now();
const receipt: Record<string, unknown> = { schemaVersion: 1, issue: 164, step: 1, scoringRun: false,
  recordedAt: new Date().toISOString(), code, codeHashes, storageRoot,
  runtime: process.version, machine: { arch: arch(), platform: platform() },
  boundary: "fixture rebuild and pinned materialized input artifacts only; no real evaluation; disposable local PostgreSQL",
  verdict: "running" };
try {
  await withFeatureStoreDatabase(async context => {
    receipt.database = (await context.admin.query("SELECT version() AS version")).rows[0].version;
    const fixture = await prepareEvaluationFixture(context, store, code, event => console.log(JSON.stringify(event)));
    receipt.preregistration = fixture.pins.preregistration;
    receipt.inputPinsArtifact = fixture.inputPinsArtifact;
    receipt.sourceManifestSha256 = fixture.pins.sourceManifestSha256;
    receipt.wireFiles = fixture.pins.inputs.length;
    receipt.ingestionCheckpoint = fixture.pins.ingestionCheckpoint;
    receipt.versions = fixture.pins.versions;
    receipt.modes = fixture.prepared.map(({ mode, dataset, spec, coverageSummary, coverageArtifact, readWork }) => ({
      mode, datasetId: dataset.datasetId, datasetObjectKey: dataset.objectKey,
      fileSha256: dataset.fileSha256, contentSha256: dataset.contentSha256,
      rowCount: dataset.rowCount, byteSize: dataset.byteSize, exclusions: dataset.exclusions, spec,
      coverageArtifact, coverage: coverageSummary,
      work: { buildStatements: 8, cohortRead: readWork },
    }));
    receipt.verdict = "pass";
  });
} catch (error) {
  receipt.verdict = "fail";
  receipt.failure = String(error);
  process.exitCode = 1;
} finally {
  receipt.elapsedMs = performance.now() - started;
  receipt.peakRssBytes = process.resourceUsage().maxRSS * 1024;
  const full = Buffer.from(JSON.stringify(receipt) + "\n");
  const key = objectKey("audits", full);
  await store.putIfAbsent(key, full);
  receipt.fullReceipt = { objectKey: key, sha256: sha256(full), byteSize: full.byteLength };
  const directory = new URL("docs/evidence/feature-store-164/", EVALUATION_ROOT);
  await mkdir(directory, { recursive: true });
  // Compact checkpoint receipts are the only generated bytes written into Git.
  await writeFile(new URL(receipt.verdict === "pass" ? "step-1-input-pins.json" : "step-1-failure.json", directory), JSON.stringify(receipt, null, 2) + "\n");
}
console.log(JSON.stringify({ verdict: receipt.verdict, storageRoot, elapsedMs: receipt.elapsedMs }));

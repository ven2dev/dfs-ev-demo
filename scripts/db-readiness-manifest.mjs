import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { checkMigrationArtifacts, buildManifest } from "./db-migrations/files.mjs";
import { loadCatalogContracts } from "./db-migrations/contracts.mjs";

const policyFile = new URL("../db/readiness.json", import.meta.url);
const outputFile = new URL("../src/lib/dbReadinessManifest.ts", import.meta.url);

export function buildReadinessManifest(manifest, contracts, policy) {
  const minimumVersion = policy?.minimumVersion;
  if (Object.keys(policy ?? {}).join(",") !== "minimumVersion" ||
      !Number.isInteger(minimumVersion) || minimumVersion < 1 || minimumVersion > manifest.migrations.length) {
    throw new Error("invalid-readiness-minimum-version");
  }
  const requiredTables = contracts.migrations[minimumVersion - 1].objects
    .filter((object) => object.kind === "relation" && ["r", "p"].includes(object.definition.kind))
    .map((object) => object.name).sort();
  if (!requiredTables.length || requiredTables.some((name) => !/^[a-z][a-z0-9_]*$/.test(name))) {
    throw new Error("invalid-readiness-table-contract");
  }
  return { minimumVersion, maximumKnownVersion: manifest.migrations.length,
    runnerVersion: manifest.runnerVersion, migrations: manifest.migrations, requiredTables };
}

export const readinessManifestText = (manifest) =>
  "// Generated by npm run db:readiness:generate. Do not edit.\n" +
  "// Runtime data only: no SQL files, catalog definitions or migration tooling.\n" +
  "export const DB_READINESS_MANIFEST = " + JSON.stringify(manifest, null, 2) + " as const;\n";

export async function readinessManifestArtifact(mode, { policyPath = policyFile, outputPath = outputFile } = {}) {
  if (!["check", "generate"].includes(mode)) throw new Error("invalid-readiness-artifact-command");
  const files = await checkMigrationArtifacts();
  const contracts = await loadCatalogContracts(files);
  const policy = JSON.parse(await readFile(policyPath, "utf8"));
  const expected = readinessManifestText(buildReadinessManifest(buildManifest(files), contracts, policy));
  if (mode === "generate") await writeFile(outputPath, expected);
  else if (await readFile(outputPath, "utf8") !== expected) throw new Error("readiness-manifest-drift");
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const [mode, ...extra] = process.argv.slice(2);
    if (extra.length) throw new Error("invalid-readiness-artifact-command");
    await readinessManifestArtifact(mode);
    process.stdout.write("Database readiness manifest " + (mode === "generate" ? "generated" : "verified") + ".\n");
  } catch {
    process.stderr.write("db-readiness-manifest: artifact-check-failed\n");
    process.exitCode = 1;
  }
}
